#!/usr/bin/env python3
"""Extract constant tables from the Schism Tracker C source into JS modules.

Usage: tools/gen-data.py [path-to-schismtracker]   (default ../schismtracker)
Writes js/gen/*.js. Data only; behaviour is hand-ported in js/*.js.
"""
import ast, base64, json, re, sys
from pathlib import Path

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent.parent / "schismtracker")
OUT = Path(__file__).resolve().parent.parent / "js" / "gen"
OUT.mkdir(parents=True, exist_ok=True)
HDR = "// Generated by tools/gen-data.py from Schism Tracker (GPL-2.0-or-later). Do not edit.\n"

# ---- keyboard constants ------------------------------------------------------
kb = (SRC / "include/keyboard.h").read_text()
kb = re.sub(r"#if 0.*?#endif", "", kb, flags=re.S)
sc, ks, km = {}, {}, {}
for name, val in re.findall(r"SCHISM_SCANCODE_(\w+)\s*=\s*(\d+)\s*,", kb):
    sc[name] = int(val)
MASK = 1 << 30
for name, val in re.findall(r"SCHISM_KEYSYM_(\w+)\s*=\s*('(?:\\.|[^'])+'|[^,\n]+),", kb):
    val = val.strip()
    m = re.fullmatch(r"SCHISM_SCANCODE_TO_KEYSYM\(SCHISM_SCANCODE_(\w+)\)", val)
    if m:
        ks[name] = sc[m.group(1)] | MASK
    elif val.startswith("'"):
        ks[name] = ord(eval(val))
    elif re.fullmatch(r"\(?\d+\)?", val):
        ks[name] = int(val.strip("()"))
    elif name == "SCANCODE_MASK":
        ks[name] = MASK
for name, val in re.findall(r"SCHISM_KEYMOD_(\w+)\s*=\s*\(([^\n]+)\),", kb):
    m = re.fullmatch(r"1u << (\d+)", val)
    if m:
        km[name] = 1 << int(m.group(1))
    elif val == "0":
        km[name] = 0
    else:
        km[name] = eval(re.sub(r"SCHISM_KEYMOD_(\w+)", lambda g: str(km[g.group(1)]), val))
for c in "abcdefghijklmnopqrstuvwxyz":
    ks.setdefault(c, ord(c))
(OUT / "keys.js").write_text(HDR +
    "export const SCANCODE = " + json.dumps(sc) + ";\n" +
    "export const KEYSYM = " + json.dumps(ks) + ";\n" +
    "export const KEYMOD = " + json.dumps(km) + ";\n")

# ---- palettes ----------------------------------------------------------------
pal = (SRC / "schism/palettes.c").read_text()
body = pal[pal.index("struct it_palette palettes[]"):]
body = body[:body.index("\n};")]
palettes = []
for m in re.finditer(r'\{"([^"]+)",\s*\{(.*?)\}\}', body, flags=re.S):
    cols = [[int(a), int(b), int(c)] for a, b, c in re.findall(r"\{\s*(\d+),\s*(\d+),\s*(\d+)\s*\}", m.group(2))]
    assert len(cols) == 16, m.group(1)
    palettes.append({"name": m.group(1), "colors": cols})
(OUT / "palettes.js").write_text(HDR + "export const PALETTES = " + json.dumps(palettes) + ";\n")

# ---- fonts ---------------------------------------------------------------------
fonts = {p.stem.replace("-", "_"): base64.b64encode(p.read_bytes()).decode() for p in sorted((SRC / "font").glob("*.fnt"))}
(OUT / "fonts.js").write_text(HDR +
    "const b64 = " + json.dumps(fonts) + ";\n"
    "const dec = (s) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));\n"
    "export const FONTS = Object.fromEntries(Object.entries(b64).map(([k, v]) => [k, dec(v)]));\n")

# ---- font editor map and help strings -----------------------------------------
itf = (SRC / 'schism/itf.c').read_text()
body = re.search(r'itfmap_chars\[\]\s*=\s*\{(.*?)\};', itf, re.S).group(1)
chars = [ord(ast.literal_eval(v.strip())) if v.strip().startswith("'") else int(v.strip())
         for v in body.split(',') if v.strip()]
assert len(chars) == 240
exports = ['export const itfmap_chars = ' + json.dumps(chars) + ';\n']
for name, body in re.findall(r'static const uint8_t (helptext_\w+)\[\]\s*=\s*(.*?);', itf, re.S):
    value = ''.join(ast.literal_eval(s) for s in re.findall(r'"(?:\\.|[^"\\])*"', body))
    exports.append('export const ' + name + ' = ' + json.dumps(value) + ';\n')
(OUT / 'itf.js').write_text(HDR + ''.join(exports))

# ---- help text (same order as the enum in page.h / Makefile.am) ----------------
mk = (SRC / "Makefile.am").read_text()
names = re.findall(r"helptext/([\w-]+)", mk[mk.index("helptexts = "):mk.index("fonts = ")])
help_texts = [(SRC / "helptext" / n).read_bytes().decode("latin-1") for n in names]
(OUT / "helptext.js").write_text(HDR +
    "export const HELP_NAMES = " + json.dumps(names) + ";\n" +
    "export const HELP_TEXT = " + json.dumps(help_texts) + ";\n")

print(f"keys: {len(sc)} scancodes, {len(ks)} keysyms, {len(km)} mods; palettes: {len(palettes)}; fonts: {list(fonts)}; help: {names}")

# ---- voice scalar layout -----------------------------------------------------
sndfile = (SRC / 'include/player/sndfile.h').read_text()
voice = sndfile.split('typedef struct song_voice {', 1)[1].split('} song_voice_t;', 1)[0]
voice = re.sub(r'/\*.*?\*/|//[^\n]*', '', voice, flags=re.S)
fields = []
for declaration in re.findall(r'\b(?:u?int(?:16|32)_t)\s+([^;]+);', voice):
    for field in declaration.split(','):
        field = field.strip()
        if '[' not in field:
            assert re.fullmatch(r'\w+', field), field
            fields.append(field)
(OUT / 'voice.js').write_text(HDR + 'export const VOICE_SCALARS = ' + json.dumps(fields) + ';\n')

# ---- player lookup tables ----------------------------------------------------
tables = (SRC / 'player/tables.c').read_text()
tables = re.sub(r'/\*.*?\*/|//[^\n]*', '', tables, flags=re.S)
exports = []
for kind, name, count, body in re.findall(
        r'const\s+(uint8_t|uint16_t|uint32_t|int8_t|char\s*\*)\s*(\w+)\[(\d+)\]\s*=\s*\{(.*?)\};', tables, re.S):
    if kind.startswith('char'):
        values = [json.loads(s) for s in re.findall(r'"(?:\\.|[^"\\])*"', body)]
    else:
        values = [int(s.strip(), 0) for s in body.split(',') if s.strip()]
    assert len(values) == int(count), (name, len(values), count)
    exports.append('export const ' + name + ' = Object.freeze(' + json.dumps(values) + ');\n')
assert len(exports) == 14, len(exports)
(OUT / 'tables.js').write_text(HDR + ''.join(exports))

quirks_body = sndfile[sndfile.index('CSF_QUIRK_PERIODS_ARE_HERTZ'):sndfile.index('CSF_QUIRK_MAX_,')]
quirks = re.findall(r'CSF_QUIRK_(\w+)\s*,', quirks_body)
with (OUT / 'tables.js').open('a') as output:
    output.write('export const QUIRK = Object.freeze(' + json.dumps(dict((name, n) for n, name in enumerate(quirks))) + ');\n')

filters = (SRC / 'player/filters.c').read_text()
resonance = re.search(r'resonance_table\[128\]\s*=\s*\{(.*?)\};', filters, re.S).group(1)
resonance = [float(value.strip().removesuffix('f')) for value in resonance.split(',') if value.strip()]
assert len(resonance) == 128
with (OUT / 'tables.js').open('a') as output:
    output.write('export const resonance_table = new Float32Array(' + json.dumps(resonance) + ');\n')

fx = {name: int(value, 0) for name, value in re.findall(r'^#define FX_(\w+)\s+(0x[0-9A-Fa-f]+|\d+)\b', sndfile, re.M)}
with (OUT / 'tables.js').open('a') as output:
    output.write('export const FX = Object.freeze(' + json.dumps(fx) + ');\n')

volfx = {name: int(value, 0) for name, value in re.findall(r'^#define VOLFX_(\w+)\s+(0x[0-9A-Fa-f]+|\d+)\b', sndfile, re.M)}
with (OUT / 'tables.js').open('a') as output:
    output.write('export const VOLFX = Object.freeze(' + json.dumps(volfx) + ');\n')

sndmix = (SRC / 'player/sndmix.c').read_text()
gmvol = re.search(r'GMvolTransition\[128\]\s*=\s*\{(.*?)\};', sndmix, re.S).group(1)
gmvol = [int(value.strip()) for value in gmvol.split(',') if value.strip()]
assert len(gmvol) == 128
with (OUT / 'tables.js').open('a') as output:
    output.write('export const GMvolTransition = Object.freeze(' + json.dumps(gmvol) + ');\n')

lut = (SRC / 'include/player/precomp_lut.h').read_text()
exports = []
for name, count, body in re.findall(r'static int16_t (\w+)\[(\d+)\]\s*=\s*\{(.*?)\};', lut, re.S):
    values = [int(value.strip()) for value in body.split(',') if value.strip()]
    assert len(values) == int(count), name
    exports.append('export const ' + name + ' = new Int16Array(' + json.dumps(values) + ');\n')
assert len(exports) == 2
(OUT / 'interpolation.js').write_text(HDR + ''.join(exports))

csndfile = (SRC / 'player/csndfile.c').read_text()
s3m_body = csndfile.split('void csf_import_s3m_effect(', 1)[1].split('void csf_export_s3m_effect(', 1)[0]
s3m_effects = {letter: fx[name] for letter, name in re.findall(r"case '([A-Z])':\s*effect = FX_(\w+)", s3m_body)}
assert len(s3m_effects) == 26
with (OUT / 'tables.js').open('a') as output:
    output.write('export const S3M_EFFECTS = Object.freeze(' + json.dumps(s3m_effects) + ');\n')

# ---- AdLib General MIDI patch bank (player/fmpatches.c) ---------------------
fmp = re.sub(r'/\*.*?\*/|//[^\n]*', '', (SRC / 'player/fmpatches.c').read_text(), flags=re.S)
body = re.search(r'patches\[\]\[11\]\s*=\s*\{(.*?)\};', fmp, re.S).group(1)
rows = [[int(v.strip(), 0) for v in row.split(',') if v.strip()] for row in re.findall(r'\{([^{}]*)\}', body)]
assert len(rows) == 128 and all(len(r) == 11 for r in rows), (len(rows),)
(OUT / 'fmpatches.js').write_text(HDR + 'export const fm_patches = Object.freeze(' + json.dumps(rows) + '.map(r => Uint8Array.from(r)));\n')
